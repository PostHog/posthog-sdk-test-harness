#!/usr/bin/env python3
"""Write the Gherkin /flags?v=4 read features from the feature flag rules v2 contract.

The scenarios are the YAML ``feature_flags_v4`` suite, one per fixture case. Each
scenario shows its mock /flags body and expected result inline, so the feature reads
without the contract. ``posthog_test_harness.flags_v4`` builds both, as it does for the
YAML suite.

    bin/update-flags-v4-features.py --specs /path/to/sdk-specs          # write
    bin/update-flags-v4-features.py --specs /path/to/sdk-specs --check  # fail on drift
"""

import argparse
import json
import sys
from pathlib import Path
from typing import Any, Dict, List

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from posthog_test_harness import flags_v4  # noqa: E402

DIRECTORY = "migration/yaml-parity-v1"
TOKEN = "phc_test_key"
DISTINCT_ID = "flags-v4-person"
INDENT = "    "

HEADER = """\
# Generated by bin/update-flags-v4-features.py in PostHog/posthog-sdk-test-harness
# from the feature_flag_rules_v2 contract {version}: fixtures/wire/readers.json and
# the successful cases of corpus/v2_value_evaluation.json. Do not edit by hand.
# Change the contract, then run the script with --specs pointing at this checkout.
"""

BACKGROUND = """\
  Background:
    Given an isolated SDK with empty persistent storage
    And the mock PostHog server is reset
    And the server uses its native flag startup and getter behavior with no installed local definitions or results
"""

FEATURES: Dict[str, Dict[str, Any]] = {
    "remote-flags-v4-legacy-getter.feature": {
        "tags": "@migration @yaml_parity_v1 @requires:flags_response_v4 @sdk:server",
        "title": "Legacy flag getter reads /flags?v=4 records",
        "description": [
            "The existing getter returns the legacy rendering of a v4 record's value:",
            "booleans and strings as is, null as false, numbers and objects as true. A",
            "failed or unreadable record returns false, and a missing flag returns no",
            "value. An older server's record without `value` reads as `variant ?? enabled`.",
            "Unknown fields, malformed sibling records and a `value` beside stale",
            "`enabled`/`variant` fields do not change the result. Types are strict:",
            'true is not 1, and the string "false" is not false.',
        ],
        "sources": [("readers", "reader fixture"), ("values", "typed value")],
        "read": "getter",
    },
    "remote-flags-v4-legacy-payload.feature": {
        "tags": ("@migration @yaml_parity_v1 @requires:flags_response_v4 @requires:feature_flag_payloads @sdk:server"),
        "title": "Legacy flag payload getter reads /flags?v=4 records",
        "description": [
            "The existing payload getter returns a config version 2 number or object",
            "value as the payload, because the server sends a null `metadata.payload`",
            "for config version 2. A boolean, string or null value has no payload. A",
            "config version 1 record and an older server's record keep their decoded",
            "`metadata.payload`. A missing flag, and a failed or unreadable record",
            "without a payload, have no payload. Payloads compare as parsed JSON values:",
            "key order and number spelling may differ, JSON types may not.",
            "",
            "A failed record that still carries a `metadata.payload` is not checked: the",
            "contract does not say whether the legacy payload getter returns it.",
        ],
        "sources": [("reader_payloads", "reader fixture"), ("values", "typed value")],
        "read": "payload",
    },
}


def dumps(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False)


def doc_string(value: Any, indent: str) -> List[str]:
    """A JSON doc string, indented under its step."""
    lines = [f'{indent}"""application/json']
    lines += [f"{indent}{line}" for line in json.dumps(value, indent=2, ensure_ascii=False).splitlines()]
    lines.append(f'{indent}"""')
    return lines


def described(value: Any) -> str:
    return "an object value" if isinstance(value, dict) else f"value {dumps(value)}"


def explanation(source: str, case_id: str, read: str) -> str:
    """One line on why the case expects its result."""
    expected = flags_v4.expectation(source, case_id)
    record = flags_v4.response(source, case_id).get("flags", {}).get(expected["key"])
    reader = flags_v4.reader(case_id) if source == "readers" else {"error_code": None, "config_version": 2}
    error_code = reader["error_code"]
    result = "the getter returns false" if read == "getter" else "the payload getter returns no payload"
    if error_code == "FLAG_NOT_FOUND":
        missing = "the getter returns no value" if read == "getter" else "the payload getter returns no payload"
        return f"The response has no record for the requested flag, so {missing}."
    if error_code is not None:
        return f"The reader reports {error_code} for the record, so {result}."
    if read == "getter":
        legacy = dumps(expected["legacy_value"])
        if "value" not in record:
            return f"An older server's record has no value, so it reads as variant ?? enabled: {legacy}."
        if isinstance(record["value"], dict):
            return f"An object record value renders as {legacy}."
        return f"The record value {dumps(record['value'])} renders as {legacy}."
    if "value" not in record or reader["config_version"] == 1:
        kind = "An older server's record" if "value" not in record else "A config version 1 record"
        if expected["legacy_payload"] is None:
            return f"{kind} has a null metadata.payload, so it has no payload."
        return f"{kind} keeps its decoded metadata.payload."
    if expected["legacy_payload"] is None:
        return f"A config version 2 record with {described(record['value'])} has no payload."
    return f"A config version 2 record with {described(record['value'])} has that value as its payload."


def scenario(source: str, label: str, case_id: str, read: str) -> List[str]:
    response_source = "readers" if source == "reader_payloads" else source
    expected = flags_v4.expectation(response_source, case_id)
    noun = "getter" if read == "getter" else "payload getter"
    step = INDENT + "  "
    lines = [
        f"  Scenario: Legacy {noun} reads {label} {case_id}",
        f"{INDENT}{explanation(response_source, case_id, read)}",
        "",
        f"{INDENT}When the mock serves this /flags response body:",
        *doc_string(flags_v4.response(response_source, case_id), step),
        f'{INDENT}And the SDK is initialized with token "{TOKEN}" and no additional configuration',
        f"{INDENT}And get feature flag{' payload' if read == 'payload' else ''} is called with JSON arguments:",
        *doc_string({"distinct_id": DISTINCT_ID, "key": expected["key"]}, step),
    ]
    if read == "getter":
        value = expected["legacy_value"]
        if value is None:
            lines.append(f"{INDENT}And the public flag getter should return no value")
        else:
            lines.append(f"{INDENT}And the public flag getter should return exactly JSON {dumps(value)}")
    else:
        payload = expected["legacy_payload"]
        if payload is None:
            lines.append(f"{INDENT}And the public flag payload getter should return no payload")
        elif isinstance(payload, (dict, list)):
            lines.append(f"{INDENT}And the public flag payload getter should return this JSON:")
            lines += doc_string(payload, step)
        else:
            lines.append(f"{INDENT}And the public flag payload getter should return JSON {dumps(payload)}")
    return lines


def render(name: str) -> str:
    feature = FEATURES[name]
    version = flags_v4.contract_version()
    lines = [HEADER.format(version=version) + feature["tags"], f"Feature: {feature['title']}"]
    lines += [f"  {line}".rstrip() for line in feature["description"]]
    lines += ["", BACKGROUND.rstrip("\n")]
    for source, label in feature["sources"]:
        for case_id in flags_v4.case_ids(source):
            lines += ["", *scenario(source, label, case_id, feature["read"])]
    return "\n".join(lines) + "\n"


def rendered() -> Dict[str, str]:
    """Feature path (relative to an sdk-specs checkout) to content."""
    return {f"{DIRECTORY}/{name}": render(name) for name in FEATURES}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--specs", required=True, type=Path, help="sdk-specs checkout")
    parser.add_argument("--check", action="store_true", help="fail if a feature differs, without writing")
    args = parser.parse_args()
    stale = []
    for path, content in rendered().items():
        target = args.specs / path
        if args.check:
            if not target.is_file() or target.read_text(encoding="utf-8") != content:
                stale.append(path)
        else:
            target.write_text(content, encoding="utf-8")
    if stale:
        print(
            "Out of date; run bin/update-flags-v4-features.py --specs <checkout>:", *stale, sep="\n  ", file=sys.stderr
        )
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
